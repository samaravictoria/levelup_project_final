-- oracle_tasks_schema.sql
CREATE USER LEVELUP IDENTIFIED BY levelup123
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON USERS;

GRANT CONNECT, RESOURCE TO LEVELUP;
GRANT CREATE SESSION TO LEVELUP;
GRANT UNLIMITED TABLESPACE TO LEVELUP;
GRANT CREATE TABLE, CREATE SEQUENCE, CREATE PROCEDURE, CREATE VIEW TO LEVELUP;

CONNECT LEVELUP/levelup123;

CREATE TABLE tasks (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  team_id NUMBER,
  assigned_by VARCHAR2(100),
  title VARCHAR2(300),
  description CLOB,
  type VARCHAR2(50),
  xp NUMBER,
  due_in_minutes NUMBER,
  metadata CLOB,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);